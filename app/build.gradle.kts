/**
 * Release signing is driven either by a local `keystore.properties` file (developer machines)
 * or by environment variables exported from GitHub Secrets in CI. When neither is present the
 * release variant simply stays unsigned so that `assembleRelease` still works locally.
 */
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        FileInputStream(keystorePropertiesFile).use { load(it) }
    }
}

fun signingValue(propKey: String, envKey: String): String? =
    keystoreProperties.getProperty(propKey) ?: System.getenv(envKey)

val releaseStoreFilePath = signingValue("storeFile", "KEYSTORE_FILE")
val hasReleaseSigning = releaseStoreFilePath != null && file(releaseStoreFilePath).exists()

